# =============================================================================
# 8. Clean participant records
# =============================================================================

participants <- participants_raw |>
  transmute(
    name_raw = as.character(
      Name
    ),
    
    Name = clean_display_name(
      clean_person_name(
        Name
      )
    ),
    
    match_key = first_last_key(
      Name
    ),
    
    duration_min = duration_to_minutes(
      `In-Meeting Duration`
    ),
    
    camera_on = suppressWarnings(
      as.numeric(
        `Engagement: Camera On`
      )
    ) |>
      replace_na(0),
    
    hand_raise = suppressWarnings(
      as.numeric(
        `Engagement: Raise Hands`
      )
    ) |>
      replace_na(0),
    
    unmute = suppressWarnings(
      as.numeric(
        `Engagement: Unmute`
      )
    ) |>
      replace_na(0)
  ) |>
  filter(
    !is.na(Name),
    Name != "",
    
    !str_detect(
      Name,
      regex(
        "read\\.ai|meeting notes|notetaker|otter",
        ignore_case = TRUE
      )
    )
  )


# =============================================================================
# 9. Reconcile reconnects
# =============================================================================

people <- participants |>
  group_by(
    match_key
  ) |>
  summarise(
    Name = first(
      Name
    ),
    
    duration_min = sum(
      duration_min,
      na.rm = TRUE
    ),
    
    camera_on = sum(
      camera_on,
      na.rm = TRUE
    ),
    
    hand_raise = sum(
      hand_raise,
      na.rm = TRUE
    ),
    
    unmute = sum(
      unmute,
      na.rm = TRUE
    ),
    
    .groups = "drop"
  ) |>
  mutate(
    is_room = str_detect(
      Name,
      regex(
        "conference room|meeting room",
        ignore_case = TRUE
      )
    ),
    
    any_camera = camera_on > 0,
    any_hand_raise = hand_raise > 0,
    any_unmute = unmute > 0
  ) |>
  arrange(
    Name
  )


# =============================================================================
# 10. Meeting summary
# =============================================================================

headline <- people |>
  summarise(
    connections = n(),
    
    room_connections = sum(
      is_room,
      na.rm = TRUE
    ),
    
    median_minutes = median(
      duration_min,
      na.rm = TRUE
    ),
    
    pct_60min_plus = mean(
      duration_min >= 60,
      na.rm = TRUE
    ),
    
    pct_camera = mean(
      any_camera,
      na.rm = TRUE
    ),
    
    pct_unmute = mean(
      any_unmute,
      na.rm = TRUE
    ),
    
    pct_hand_raise = mean(
      any_hand_raise,
      na.rm = TRUE
    )
  )


