duration_to_minutes <- function(x) {
  
  x <- replace_na(
    as.character(x),
    ""
  )
  
  hours <- str_extract(
    x,
    "\\d+(?=h)"
  ) |>
    replace_na("0") |>
    as.numeric()
  
  mins <- str_extract(
    x,
    "\\d+(?=m)"
  ) |>
    replace_na("0") |>
    as.numeric()
  
  secs <- str_extract(
    x,
    "\\d+(?=s)"
  ) |>
    replace_na("0") |>
    as.numeric()
  
  60 * hours + mins + secs / 60
}


credential_pattern <- paste0(
  "\\b(",
  paste(
    c(
      "MD",
      "DO",
      "PhD",
      "Ph\\.D",
      "MPH",
      "MBA",
      "MS",
      "MSc",
      "CNP",
      "NP",
      "PA-C",
      "PA",
      "RN",
      "BSN",
      "MSN",
      "FACS",
      "FAAD",
      "FACEP"
    ),
    collapse = "|"
  ),
  ")\\b\\.?"
)


clean_person_name <- function(x) {
  
  x <- x |>
    replace_na("") |>
    str_replace_all("[\u2018\u2019]", "'") |>
    str_remove_all("\\s*\\([^)]*\\)") |>
    str_remove_all("\\s*\\[[^]]*\\]") |>
    str_replace_all(
      regex(
        credential_pattern,
        ignore_case = TRUE
      ),
      ""
    ) |>
    str_replace_all("\\s+", " ") |>
    str_squish()
  
  map_chr(
    x,
    function(nm) {
      
      if (is.na(nm) || nm == "") {
        return(NA_character_)
      }
      
      pieces <- str_split(
        nm,
        ",",
        simplify = FALSE
      )[[1]] |>
        str_squish()
      
      pieces <- pieces[
        pieces != ""
      ]
      
      # Teams frequently exports names as:
      # Last, First Middle, credentials
      #
      # Credential text has already been removed above.
      if (length(pieces) >= 2) {
        
        last <- pieces[1]
        
        given <- paste(
          pieces[-1],
          collapse = " "
        )
        
        nm <- str_squish(
          paste(
            given,
            last
          )
        )
      }
      
      nm |>
        str_replace_all("\\s*,\\s*", " ") |>
        str_replace_all("\\s+", " ") |>
        str_squish()
    }
  )
}


first_last_key <- function(x) {
  
  clean <- clean_person_name(x)
  
  map_chr(
    clean,
    function(nm) {
      
      if (is.na(nm) || nm == "") {
        return(NA_character_)
      }
      
      words <- nm |>
        str_to_lower() |>
        str_replace_all(
          "[^a-z0-9' -]",
          " "
        ) |>
        str_squish() |>
        str_split(
          "\\s+",
          simplify = FALSE
        )
      
      words <- words[[1]]
      words <- words[
        words != ""
      ]
      
      if (length(words) == 0) {
        return(NA_character_)
      }
      
      if (length(words) == 1) {
        
        return(
          str_replace_all(
            words,
            "[^a-z0-9]",
            ""
          )
        )
      }
      
      paste0(
        str_replace_all(
          words[1],
          "[^a-z0-9]",
          ""
        ),
        str_replace_all(
          words[length(words)],
          "[^a-z0-9]",
          ""
        )
      )
    }
  )
}


clean_display_name <- function(x) {
  
  case_when(
    str_detect(
      str_to_lower(x),
      "vernon.*sondak"
    ) ~ "Vern Sondak",
    
    str_detect(
      str_to_lower(x),
      "sorrentino"
    ) ~ "Alex Sorrentino",
    
    str_detect(
      str_to_lower(x),
      "ken tsai"
    ) ~ "Ken Tsai",
    
    str_detect(
      str_to_lower(x),
      "^dl$"
    ) ~ "Don Lawrence",
    
    str_detect(
      str_to_lower(x),
      "oak conference room"
    ) ~ "Replimune team",
    
    TRUE ~ x
  )
}


# =============================================================================
# 4. Read Teams report
# =============================================================================

ext <- tolower(
  tools::file_ext(
    attendance_file
  )
)


if (ext %in% c("xls", "xlsx")) {
  
  # ---------------------------------------------------------------------------
  # Excel Teams export
  # ---------------------------------------------------------------------------
  
  raw <- readxl::read_excel(
    attendance_file,
    col_names = FALSE,
    col_types = "text",
    .name_repair = "minimal"
  )
  
  raw <- as_tibble(
    raw,
    .name_repair = "minimal"
  )
  
} else {
  
  # ---------------------------------------------------------------------------
  # Teams "CSV" export
  #
  # These files may actually be:
  #   * UTF-16LE
  #   * tab-delimited
  #   * variable-width by section
  #
  # readr/vroom can occasionally treat the entire line as one field.
  # We therefore read the text ourselves and split each line explicitly.
  # ---------------------------------------------------------------------------
  
  con <- file(
    attendance_file,
    open = "r",
    encoding = "UTF-16LE"
  )
  
  on.exit(
    close(con),
    add = TRUE
  )
  
  lines <- readLines(
    con,
    warn = FALSE
  )
  
  # Remove UTF BOM if it survives decoding.
  if (length(lines) > 0) {
    lines[1] <- sub(
      "^\ufeff",
      "",
      lines[1]
    )
  }
  
  split_lines <- strsplit(
    lines,
    "\t",
    fixed = TRUE
  )
  
  max_cols <- max(
    lengths(split_lines)
  )
  
  padded <- lapply(
    split_lines,
    function(x) {
      
      length(x) <- max_cols
      
      x[
        is.na(x)
      ] <- ""
      
      x
    }
  )
  
  raw <- as_tibble(
    do.call(
      rbind,
      padded
    ),
    .name_repair = "minimal"
  )
}


# Give every imported column a safe temporary name before using dplyr.
names(raw) <- paste0(
  "col_",
  seq_len(
    ncol(raw)
  )
)

# Convert every cell to clean text.
raw <- raw |>
  mutate(
    across(
      everything(),
      ~ replace_na(
        as.character(.x),
        ""
      ) |>
        str_squish()
    )
  )

message(
  "Imported rows: ",
  nrow(raw)
)

message(
  "Imported columns: ",
  ncol(raw)
)


# =============================================================================
# 5. Locate Teams sections robustly
# =============================================================================

# Search the entire row, not just the first column.
row_text <- apply(
  as.data.frame(raw),
  1,
  function(z) {
    
    paste(
      z[
        z != ""
      ],
      collapse = " | "
    ) |>
      str_squish()
  }
)


participants_section <- which(
  str_detect(
    row_text,
    regex(
      "(^|\\|\\s*)2\\.\\s*Participants\\b",
      ignore_case = TRUE
    )
  )
)[1]


activities_section <- which(
  str_detect(
    row_text,
    regex(
      "(^|\\|\\s*)3\\.\\s*In[- ]Meeting Activities\\b",
      ignore_case = TRUE
    )
  )
)[1]


if (
  is.na(participants_section) ||
  is.na(activities_section)
) {
  
  likely_rows <- which(
    str_detect(
      row_text,
      regex(
        "participant|meeting activit|duration|camera|unmute|raise",
        ignore_case = TRUE
      )
    )
  )
  
  preview <- paste(
    paste0(
      likely_rows,
      ": ",
      row_text[
        likely_rows
      ]
    ),
    collapse = "\n"
  )
  
  stop(
    paste0(
      "Could not identify the Teams participant/activity sections.\n\n",
      "Rows containing likely attendance keywords:\n",
      preview
    )
  )
}


if (activities_section <= participants_section) {
  
  stop(
    paste0(
      "Teams section order is unexpected: Participants row = ",
      participants_section,
      "; Activities row = ",
      activities_section
    )
  )
}


message(
  "Participants section row: ",
  participants_section
)

message(
  "Activities section row: ",
  activities_section
)


# =============================================================================
# 6. Locate participant header row
# =============================================================================

candidate_header_rows <- seq(
  participants_section + 1,
  activities_section - 1
)


expected_headers <- c(
  "Name",
  "First Join",
  "Last Leave",
  "In-Meeting Duration",
  "Email",
  "Participant ID",
  "Participant ID (UPN)",
  "Role",
  "Engagement: Reaction-Applause",
  "Engagement: Reaction-Laugh",
  "Engagement: Reaction-Like",
  "Engagement: Reaction-Love",
  "Engagement: Reaction-Surprised",
  "Engagement: Camera On",
  "Engagement: Raise Hands",
  "Engagement: Unmute",
  "Reactions"
)


header_scores <- map_int(
  candidate_header_rows,
  function(i) {
    
    vals <- unlist(
      raw[
        i,
        ,
        drop = FALSE
      ],
      use.names = FALSE
    ) |>
      as.character() |>
      str_squish()
    
    sum(
      vals %in% expected_headers
    )
  }
)


header_row <- candidate_header_rows[
  which.max(
    header_scores
  )
]


if (
  length(header_row) == 0 ||
  max(header_scores) < 2
) {
  
  candidate_preview <- paste(
    paste0(
      candidate_header_rows,
      ": ",
      row_text[
        candidate_header_rows
      ]
    ),
    collapse = "\n"
  )
  
  stop(
    paste0(
      "Could not identify the Teams participant header row.\n\n",
      "Candidate rows between Participants and Activities:\n",
      candidate_preview
    )
  )
}


message(
  "Participant header row: ",
  header_row
)


header <- raw[
  header_row,
  ,
  drop = FALSE
] |>
  unlist(
    use.names = FALSE
  ) |>
  as.character() |>
  str_squish()


empty_header <- is.na(header) |
  header == ""


header[
  empty_header
] <- paste0(
  "X",
  which(
    empty_header
  )
)


header <- make.unique(
  header
)


# =============================================================================
# 7. Extract participant rows
# =============================================================================

participant_rows <- seq(
  header_row + 1,
  activities_section - 1
)


participants_raw <- raw[
  participant_rows,
  ,
  drop = FALSE
]


names(
  participants_raw
) <- header


required <- c(
  "Name",
  "In-Meeting Duration",
  "Engagement: Camera On",
  "Engagement: Raise Hands",
  "Engagement: Unmute"
)


missing_required <- setdiff(
  required,
